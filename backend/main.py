@app.post("/api/auth/register")
async def register_user(payload: RegisterRequest):
    email = payload.email.strip().lower()
    if email in users:
        return {"ok": False, "message": "Пользователь уже существует"}

    hashed = hashlib.sha256(payload.password.encode("utf-8")).hexdigest()
    users[email] = {
        "name": payload.name.strip(),
        "email": email,
        "password_hash": hashed,
    }
    token = secrets.token_hex(16)
    return {
        "ok": True,
        "message": "Регистрация успешна",
        "token": token,
        "user": {"name": users[email]["name"], "email": email},
    }


@app.post("/api/auth/login")
async def login_user(payload: LoginRequest):
    email = payload.email.strip().lower()
    user = users.get(email)
    if not user:
        return {"ok": False, "message": "Пользователь не найден"}

    hashed = hashlib.sha256(payload.password.encode("utf-8")).hexdigest()
    if hashed != user["password_hash"]:
        return {"ok": False, "message": "Неверный пароль"}

    token = secrets.token_hex(16)
    return {
        "ok": True,
        "message": "Вход выполнен",
        "token": token,
        "user": {"name": user["name"], "email": user["email"]},
    }


@app.post("/api/score")
async def score_test(payload: ScoreRequest):
    lang = payload.lang if payload.lang in profiles else "ru"
    scores = {"tech": 0, "science": 0, "leader": 0}
    for index, answer_index in enumerate(payload.answers):
        mapping = score_map[index] if index < len(score_map) else None
        if not mapping:
            continue
        key = mapping[answer_index] if answer_index < len(mapping) else mapping[0]
        scores[key] += 1

    best_key = max(scores, key=scores.get)
    best_score = scores[best_key]
    percentage = round(best_score / len(score_map) * 100)
    return {
        "profile": profiles[lang][best_key],
        "percentage": percentage,
        "scores": scores,
    }
